def _neg(x):
    """'= -2'처럼 등호 뒤 음수는 '= it-2'로 쓴다(사용자 1단원 수정본 기준).
    '3overline', 'koverline'처럼 수·문자에 붙은 overline은 띄어 쓴다(붙으면 한글 수식이 한 낱말로 읽는다)."""
    if isinstance(x, str):
        x = re.sub(r"(?<=[0-9A-Za-z])overline", " overline", x)
        return re.sub(r"\$([^$]*)\$", lambda m: "$" + re.sub(r"=\s*-(?=\s*[0-9a-z(])", "= it-", m.group(1)) + "$", x)
    if isinstance(x, list):
        return [_neg(v) for v in x]
    if isinstance(x, tuple):
        return tuple(_neg(v) for v in x)
    if isinstance(x, dict):
        return {k: (_neg(v) if k != "img" else v) for k, v in x.items()}
    return x


