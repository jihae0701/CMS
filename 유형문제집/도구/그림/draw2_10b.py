def pl(F, pts, extra=""):
    F.svg.append('<polyline points="%s" fill="none" stroke="#000" stroke-width="%s" stroke-linejoin="round" %s/>'
                 % (" ".join("%.1f,%.1f" % F.P(*p) for p in pts), STROKE, extra))


def fn(F, f, x0, x1, extra="", n=240):
    pl(F, [(x0 + (x1 - x0) * i / n, f(x0 + (x1 - x0) * i / n)) for i in range(n + 1)], extra)


def dash(F, p, q):
    F.seg(p, q, 1.5, DASH)


def line(F, p, q):
    F.seg(p, q, 2.0)


def xaxis_only(F):
    import draw5
    s = draw5.axes(F.P, F.xr, F.yr)
    F.svg.append(s[:s.rfind("<line")])
    X, Y = F.P(F.xr[1], 0)
    F.labels.append((X + 0.3, Y + 1.1, "x", 22, "rt"))


def O(F, anc="rt", dx=-4, dy=4):
    F.pt((0, 0), "O", anc, dx, dy)


