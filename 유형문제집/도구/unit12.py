# 한글 수식에서 'Apmatrix'는 한 낱말로 읽히므로 문자·숫자·괄호 바로 뒤의 pmatrix 앞에는 빈칸을 둔다
def _sp(x):
    if isinstance(x, str):
        return re.sub(r"(?<=[A-Za-z0-9}\)])pmatrix", " pmatrix", x)
    if isinstance(x, list):
        return [_sp(v) for v in x]
    if isinstance(x, dict):
        return {k: _sp(v) for k, v in x.items()}
    return x


