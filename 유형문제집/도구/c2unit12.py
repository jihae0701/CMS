def N(v, q, ans, sol, src="", mc=None):
    it = {"v": v, "q": q, "ans": ans, "sol": sol, "src": src}
    if mc:
        it["mc"] = mc
    return it


def _c(*v):
    return ["$%s$" % x for x in v]


def L(x):
    return " LEFT | " + x + " RIGHT | "


def S(*xs):
    return "LEFT { " + ",~".join(str(v) for v in xs) + " RIGHT }"


def C(cond, var="x"):
    return "LEFT { " + var + "`vert`" + cond + " RIGHT }"


def CS(*rows):
    return "cases{" + " # ".join("%s & (%s)" % r for r in rows) + "}"


