def N(v, q, ans, sol, src="", mc=None):
    it = {"v": v, "q": q, "ans": ans, "sol": sol, "src": src}
    if mc:
        it["mc"] = mc
    return it


def S(*xs):
    return "LEFT { " + ",~".join(str(v) for v in xs) + " RIGHT }"


def C(cond, var="x"):
    import re
    return "LEFT { " + var + "`vert`" + re.sub(r"(?<=[가-힣]) | (?=[가-힣])", "~", cond) + " RIGHT }"


def E(s):
    return "LEFT { " + s + " RIGHT }"


def _c(*v):
    return ["$%s$" % x for x in v]


